-- Архив зала славы: итоги сезонов, турниров и мини-турниров клуба по годам (с 2012, Харьков).
-- Данные собраны из группы клуба ВКонтакте; правятся владельцем/админом.
create table public.hall_of_fame (
  id bigint generated always as identity primary key,
  club_id bigint not null references public.clubs (id) on delete cascade,
  city text not null,
  year smallint not null check (year between 2000 and 2100),
  category text not null check (category in ('season', 'tournament', 'mini', 'achievement')),
  title text not null check (length(title) between 1 and 160),
  season text check (season is null or season ~ '^[IVXLC]{1,8}$'),
  places text[] not null check (cardinality(places) between 1 and 3),
  note text check (note is null or length(note) <= 300),
  sort integer not null default 100
);
create index hall_of_fame_club_year_idx on public.hall_of_fame (club_id, year desc, sort);
alter table public.hall_of_fame enable row level security;

create policy "hall of fame is public" on public.hall_of_fame for select to anon, authenticated using (true);
create policy "admins add hall entries" on public.hall_of_fame for insert to authenticated
  with check ((select private.has_club_role(club_id, array['owner', 'admin'])));
create policy "admins edit hall entries" on public.hall_of_fame for update to authenticated
  using ((select private.has_club_role(club_id, array['owner', 'admin'])))
  with check ((select private.has_club_role(club_id, array['owner', 'admin'])));
create policy "admins remove hall entries" on public.hall_of_fame for delete to authenticated
  using ((select private.has_club_role(club_id, array['owner', 'admin'])));

grant select on public.hall_of_fame to anon, authenticated;
grant insert (club_id, city, year, category, title, season, places, note, sort),
      update (city, year, category, title, season, places, note, sort), delete on public.hall_of_fame to authenticated;
grant all on public.hall_of_fame to service_role;
