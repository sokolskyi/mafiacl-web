export type City = { key: string; country: string; names: Record<"cs" | "ru" | "uk" | "en", string> };

export const CITIES_LIST: City[] = ROWS.map(([key, country, cs, ru, uk, en]) => ({ key, country, names: { cs, ru, uk, en } }));

const BY_KEY = new Map(CITIES_LIST.map((c) => [c.key, c]));

export const cityByKey = (key: string | null | undefined) => (key ? BY_KEY.get(key) ?? null : null);

/** Название города на языке страницы; старые значения (свободный текст) показываем как есть. */
export function cityLabel(value: string | null | undefined, locale: string): string | null {
  if (!value) return null;
  const c = BY_KEY.get(value);
  if (!c) return value;
  return c.names[(locale in c.names ? locale : "en") as keyof City["names"]];
}

/** Для поиска: без регистра и диакритики (Plzen → Plzeň). */
export const fold = (s: string) =>
  s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/ё/g, "е").replace(/[’'`]/g, "").toLowerCase().trim();
